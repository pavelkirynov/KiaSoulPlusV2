// ====================================================================================
// НЕГАТИВНА ВІДПОВІДЬ БЛОКА (NegativeResponse)
//
// Будь-який блок на будь-який діагностичний запит може відповісти відмовою:
// `7F <служба> <причина>`. Це властивість самого протоколу, а не якогось одного
// запиту, тож живе тут, поруч із розбором кадрів, а не в тому, хто питає.
//
// НАВІЩО ЦЕ ПОТРІБНО ТОМУ, ХТО ПИТАЄ. Дві причини з усього списку означають не
// «ні», а «ще раз»: 0x21 — «зайнятий, повтори» і 0x78 — «прийняв, готую відповідь».
// Відрізнити їх мусить саме той, хто тримає з'єднання, бо тільки він може спитати
// вдруге. Що означає решта причин — його вже не стосується: це справа того, хто
// розбирає відповідь.
//
// Чистий об'єкт без стану: перевіряється тестами.
// ====================================================================================

package com.kirianov.kiasoulevplus2.tools.frames

object NegativeResponse {

    /** Служба, до якої належить запит: це його перший байт. */
    fun serviceOf(request: String): Int? =
        request.trim().take(2).toIntOrNull(16)

    /**
     * Причина відмови на цю службу; null — відмови немає.
     *
     * Шукається не з початку, а по всьому кадру: у відповіді можуть бути залишки
     * попереднього обміну, ехо запиту чи текст адаптера.
     */
    fun codeOf(rawResponse: String, service: Int): Int? {
        val bytes = FrameParser.parse(rawResponse)
        for (at in 0 until bytes.size - 2) {
            if (bytes[at] == NEGATIVE && bytes[at + 1] == service) return bytes[at + 2]
        }
        return null
    }

    /**
     * Чи блок попросив спитати ще раз.
     *
     * Живий приклад із машини: датчики тиску відповіли 0x78, підсилювач керма —
     * 0x21, і обидва тоді пішли в звіт як «відмовив». Насправді жоден з них не
     * відмовляв.
     */
    fun busy(rawResponse: String, request: String): Boolean {
        val service = serviceOf(request) ?: return false
        return codeOf(rawResponse, service) in BUSY_CODES
    }

    /**
     * Чи відповідь узагалі щось несе: блок озвався і не відмовив.
     *
     * Потрібно тому, хто питає, а не тому, хто розбирає: якщо блок уже відповів
     * по суті, питати його ще й другою мовою немає сенсу — а кожен зайвий запит
     * до мовчазної адреси коштує секунди на таймауті.
     */
    fun answeredWithData(rawResponse: String, request: String): Boolean {
        if (FrameParser.parse(rawResponse).isEmpty()) return false
        val service = serviceOf(request) ?: return false
        return codeOf(rawResponse, service) == null
    }

    /** «Зайнятий, повтори» і «прийняв, готую відповідь». */
    private val BUSY_CODES = setOf(0x21, 0x78)

    private const val NEGATIVE = 0x7F
}
