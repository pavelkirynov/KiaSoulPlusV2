package com.kirianov.kiasoulevplus2.tools.paths

import java.io.File

object CarPaths {

    /** Тека для авто без VIN: перший запуск, або адаптер VIN не віддає. */
    const val UNKNOWN_CAR = "unknown"

    private const val CARS_DIR = "cars"

    /** Дозволені в назві теки символи. VIN інших і не містить. */
    private val ALLOWED = Regex("[^A-Za-z0-9]")

    fun directoryFor(root: File, vin: String): File =
        File(File(root, CARS_DIR), folderName(vin))

    fun folderName(vin: String): String {
        val clean = ALLOWED.replace(vin.trim().uppercase(), "")
        return clean.ifEmpty { UNKNOWN_CAR }
    }

    /** Корінь усіх авто: потрібен переїзду старих даних і «поділитися». */
    fun carsRoot(root: File): File = File(root, CARS_DIR)
}
