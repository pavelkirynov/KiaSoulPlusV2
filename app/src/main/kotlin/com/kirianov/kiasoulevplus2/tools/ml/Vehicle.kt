// ====================================================================================
// ПАРАМЕТРИ АВТО (Vehicle)
//
// Єдине місце, де записано, що це за машина. Звідси виводяться апріорні коефіцієнти
// моделі витрати й початкове припущення про ємність. Пересадили застосунок на інше
// авто — правити треба тільки тут.
//
// ГОЛОВНЕ ПРО ЦЮ МАШИНУ: батарея **перепакована** літій-залізо-фосфатними
// комірками. Кузов і привід лишилися від Soul EV 2015 року, а пакет тепер помітно
// більший за рідний 27 кВт·год.
//
// Саме звідси й береться потреба в цьому блоці, і справа не лише в розмірі пакета.
// BMS рахує відсоток за паспортом **рідних нікелевих** комірок: за їхньою кривою
// напруги і їхньою ємністю. А в LFP крива інша, і головне — майже пласка: від
// чверті до трьох чвертей заряду напруга майже не рухається. Для BMS, налаштованої
// на нікель, це означає, що в середині шкали вона «не помічає» витраченого, а на
// колінах навпаки малює великий стрибок там, де енергії мало. Через це:
//
//   • відсоток на панелі не відповідає ані енергії, ані пробігу, який лишився;
//   • «запас ходу» бортового комп'ютера порахований від чужої ємності;
//   • розбіжність **нелінійна по шкалі**: сталим коефіцієнтом її не виправити,
//     потрібна саме крива. Її і вимірює `CapacityModel`, корзина за корзиною.
//
// Дозволене BMS вікно заряду вужче за фізичне — і хай так: воно береже комірки від
// повного заряду й повного розряду. Шкала на екрані свідомо збігається з цим
// вікном: нуль і сто на екрані — це нуль і сто, які дозволяє авто.
//
// Тому ємність тут — не константа, а **апріорне припущення**, яке модель дуже
// швидко замінює виміряним: вага однієї сесії заряду більша за вагу цього приору
// в тисячі разів. Число нижче потрібне рівно на перший день, поки жодної сесії ще
// не було.
// ====================================================================================

package com.kirianov.kiasoulevplus2.tools.ml

internal object Vehicle {

    /**
     * Корисна ємність перепакованої батареї, кВт·год. Оцінка власника: 40–50.
     *
     * Це апріорі, а не істина: справжнє значення блок вивчає з пар «скільки з'їхало
     * SOC / скільки на це пішло енергії». Апріорна σ (див. `CapacityModel`) навмисно
     * широка — 4 кВт·год, тобто «десь між 37 і 53», — щоб перша ж сесія заряду
     * переважила цю цифру.
     */
    const val USABLE_CAPACITY_KWH = 45.0

    /**
     * Рідний пакет, за паспортом якого досі рахує BMS. Потрібен лише для одного:
     * показати, у скільки разів перепаковка більша за те, від чого відштовхується
     * приладова панель. Саме це відношення й пояснює, чому вона так помиляється.
     */
    const val ORIGINAL_CAPACITY_KWH = 27.0

    // --- Кузов і привід: від них залежить витрата, і вони перепаковкою не змінилися ---

    /** Спорядженя маса з водієм, кг. Рідні 1492 плюс важчий пакет. */
    const val MASS_KG = 1620.0

    /** Cx·A, м². Soul — цеглина: 0.35 × 2.58. */
    const val DRAG_AREA_M2 = 0.90

    const val ROLLING_RESISTANCE = 0.012

    /** ККД тракту «батарея → колесо». */
    const val DRIVETRAIN_EFFICIENCY = 0.87

    private const val AIR_DENSITY = 1.2
    private const val GRAVITY = 9.81

    /** Опорна швидкість, від якої рахуються всі ознаки: 10 м/с = 36 км/год. */
    const val SPEED_REFERENCE_MPS = 10.0

    /** Постійний відбір: борткомп'ютер, DC-DC, освітлення. Без клімату. */
    const val AUX_KW = 0.80

    /** Опір коченню на опорній швидкості, кВт: Crr·m·g·v / ККД. */
    val ROLLING_KW: Double =
        ROLLING_RESISTANCE * MASS_KG * GRAVITY * SPEED_REFERENCE_MPS / 1000.0 / DRIVETRAIN_EFFICIENCY

    /** Опір повітря на опорній швидкості, кВт: ½·ρ·CxA·v³ / ККД. */
    val DRAG_KW: Double =
        0.5 * AIR_DENSITY * DRAG_AREA_M2 *
            SPEED_REFERENCE_MPS * SPEED_REFERENCE_MPS * SPEED_REFERENCE_MPS / 1000.0 / DRIVETRAIN_EFFICIENCY

    /**
     * Пічка. Широка апріорна σ навмисно: стану клімату застосунок не бачить, і
     * температура за бортом — лише його замінник.
     */
    const val HEATING_KW = 1.20

    /** Кондиціонер. */
    const val COOLING_KW = 0.60

    /** Додаткові втрати на холодній батареї. */
    const val COLD_BATTERY_KW = 0.05
}
