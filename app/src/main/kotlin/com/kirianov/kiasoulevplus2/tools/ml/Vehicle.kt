// ====================================================================================
// ПАРАМЕТРИ АВТО (Vehicle)
//
// Єдине місце, де записано, що це за машина. Звідси виводяться апріорні коефіцієнти
// моделі витрати й початкове припущення про ємність. Пересадили застосунок на інше
// авто — правити треба тільки тут.
//
// ГОЛОВНЕ ПРО ЦЮ МАШИНУ: батарея **перепакована** іншими літій-іонними комірками.
// Кузов і привід лишилися від Soul EV 2015 року, а пакет тепер близько 51 кВт·год
// проти рідних 27 — майже вдвічі більший.
//
// Саме звідси й береться потреба в цьому блоці. BMS рахує відсоток за паспортом
// **рідних** комірок: за їхньою ємністю і їхньою таблицею напруг. Наслідків два, і
// вони різні за природою.
//
//   • Масштаб. За кожним відсотком панелі стоїть майже вдвічі більше кіловат-годин
//     і кілометрів, ніж вона рахує. Це найбільша частина розбіжності, і вона проста.
//   • Форма. Крива напруги нових комірок не тотожна рідній, тож поправка не є сталим
//     множником — вона гуляє по шкалі. **Наскільки і де саме — наперед невідомо:**
//     це залежить від того, які комірки поставлені і скільки їх у ланцюжку.
//
// Тому блок нічого не припускає про форму кривої. Він її **міряє** — корзина за
// корзиною по 10 % шкали, з пар «скільки з'їхав SOC / скільки на це пішло енергії».
// Виявиться крива майже прямою — вийде майже пряма; виявиться з горбом — вийде горб.
// Це принципово: будь-яка вгадана наперед форма була б тими самими ручними
// коефіцієнтами, тільки складнішими.
//
// Дозволене BMS вікно заряду вужче за фізичне — і хай так: воно береже комірки від
// повного заряду й повного розряду. Шкала на екрані свідомо збігається з цим
// вікном: нуль і сто на екрані — це нуль і сто, які дозволяє авто.
//
// Тому ємність тут — не константа, а **апріорне припущення**, яке модель дуже
// швидко замінює виміряним: вага однієї сесії заряду більша за вагу цього приору
// в тисячі разів. Число нижче потрібне рівно на перший день, поки жодної сесії ще
// не було.
// ====================================================================================

package com.kirianov.kiasoulevplus2.tools.ml

internal object Vehicle {

    /**
     * Ємність перепакованої батареї, кВт·год. Число від того, хто пакет збирав.
     *
     * Це апріорі, а не істина, і трактується воно як енергія всієї шкали BMS.
     * Скільки з неї дійсно доступно — визначає вікно, яке BMS дозволяє, і його
     * блок теж міряє сам. Справжнє значення вивчається з пар «скільки з'їхало SOC /
     * скільки на це пішло енергії»; апріорна σ (див. `CapacityModel`) навмисно
     * широка — близько 5 кВт·год, — щоб перша ж сесія заряду переважила цю цифру.
     */
    const val USABLE_CAPACITY_KWH = 51.0

    /**
     * Рідний пакет, за паспортом якого досі рахує BMS. Потрібен лише для одного:
     * показати, у скільки разів перепаковка більша за те, від чого відштовхується
     * приладова панель. Саме це відношення й пояснює, чому вона так помиляється.
     */
    const val ORIGINAL_CAPACITY_KWH = 27.0

    // --- Кузов і привід: від них залежить витрата, і вони перепаковкою не змінилися ---

    /** Спорядженя маса з водієм, кг. Рідні 1492 плюс важчий пакет. */
    const val MASS_KG = 1620.0

    /** Cx·A, м². Soul — цеглина: 0.35 × 2.58. */
    const val DRAG_AREA_M2 = 0.90

    const val ROLLING_RESISTANCE = 0.012

    /** ККД тракту «батарея → колесо». */
    const val DRIVETRAIN_EFFICIENCY = 0.87

    private const val AIR_DENSITY = 1.2
    private const val GRAVITY = 9.81

    /** Опорна швидкість, від якої рахуються всі ознаки: 10 м/с = 36 км/год. */
    const val SPEED_REFERENCE_MPS = 10.0

    /** Постійний відбір: борткомп'ютер, DC-DC, освітлення. Без клімату. */
    const val AUX_KW = 0.80

    /** Опір коченню на опорній швидкості, кВт: Crr·m·g·v / ККД. */
    val ROLLING_KW: Double =
        ROLLING_RESISTANCE * MASS_KG * GRAVITY * SPEED_REFERENCE_MPS / 1000.0 / DRIVETRAIN_EFFICIENCY

    /** Опір повітря на опорній швидкості, кВт: ½·ρ·CxA·v³ / ККД. */
    val DRAG_KW: Double =
        0.5 * AIR_DENSITY * DRAG_AREA_M2 *
            SPEED_REFERENCE_MPS * SPEED_REFERENCE_MPS * SPEED_REFERENCE_MPS / 1000.0 / DRIVETRAIN_EFFICIENCY

    /**
     * Скільки кіловат стоїть за одиницею частки клімату з кадру 200.
     *
     * Частка — це доля витрати, яку з'їдає клімат, тож у кіловатах вона важить
     * приблизно стільки, скільки авто споживає загалом. Число нижче — типова
     * потужність у русі; лінеаризація груба, тому апріорна σ тут найширша.
     */
    const val CLIMATE_KW_PER_SHARE = 8.0

    /**
     * Пічка за температурою за бортом. Тепер це **запасний** доданок: працює, поки
     * кадр 200 ще не приходив, і ловить залишок, якого частка не пояснила.
     */
    const val HEATING_KW = 0.60

    /** Кондиціонер. */
    const val COOLING_KW = 0.60

    /** Додаткові втрати на холодній батареї. */
    const val COLD_BATTERY_KW = 0.05
}
