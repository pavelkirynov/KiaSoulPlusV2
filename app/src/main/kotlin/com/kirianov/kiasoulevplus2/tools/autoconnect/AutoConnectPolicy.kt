// ====================================================================================
// КОЛИ ПРОБУВАТИ ПІДКЛЮЧИТИСЯ САМОСТІЙНО (AutoConnectPolicy)
//
// Моделі вчаться лише тоді, коли застосунок під'єднаний, а під'єднаний він лише
// тоді, коли хтось натиснув кнопку. Через це найцінніші дані — щоденні поїздки —
// просто не потрапляли в журнал.
//
// Уся складність тут в одному: не влаштувати нескінченний штурм адаптера. Якщо
// адаптера в машині немає, спроба провалюється за секунди, і без відступу
// застосунок молотив би Bluetooth без кінця, з'їдаючи батарею телефона.
//
// Чисті функції: розклад спроб перевіряється тестами без Bluetooth.
// ====================================================================================

package com.kirianov.kiasoulevplus2.tools.autoconnect

object AutoConnectPolicy {

    /** Перша пауза після невдачі. Коротка: адаптер міг просто не встигнути ожити. */
    const val FIRST_DELAY_MS = 5_000L

    /**
     * Далі пауза подвоюється до цієї межі. Дві хвилини — компроміс: якщо сісти в
     * машину саме зараз, підключення станеться протягом двох хвилин без жодного
     * натискання, і при цьому вночі застосунок майже не турбує Bluetooth.
     */
    const val MAX_DELAY_MS = 120_000L

    /** Як часто перевіряти стан, коли підключення вже є або користувач сам відключився. */
    const val IDLE_CHECK_MS = 5_000L

    /**
     * Пауза перед спробою номер [attempt] (перша спроба — 1).
     * Подвоєння без випадкової складової: тут один клієнт і один адаптер,
     * розводити спроби в часі не від кого.
     */
    fun delayAfter(attempt: Int): Long {
        if (attempt < 1) return FIRST_DELAY_MS
        // Зсув замість pow: 2^30 уже перевищує межу, тож переповнення не буває.
        val doublings = (attempt - 1).coerceAtMost(30)
        val delay = FIRST_DELAY_MS shl doublings
        return if (delay in 1..MAX_DELAY_MS) delay else MAX_DELAY_MS
    }
}
