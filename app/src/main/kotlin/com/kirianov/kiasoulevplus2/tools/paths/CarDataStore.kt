// перемкнутися на інше авто, віддати свої файли назовні й ПРИЙНЯТИ чужі, злившись
// із ними.
//
// ЧОМУ ІНТЕРФЕЙС, А НЕ ЗАГАЛЬНИЙ РОЗПОРЯДНИК. Файли в кожного сховища свої, і
// зливати їх треба по-різному: журнал відрізків — об'єднанням без повторів, суми
// кривої — додаванням, облік зарядок — узяти свіжіший. Спільний розпорядник мусив
// би знати всі ці правила, тобто зазирати в чужі дані. Натомість кожен зливає своє
// сам, а спільним лишається тільки те, ЩО він уміє.
//
// Живе серед спільних бібліотек: це чиста домовленість без стану, тож посилатися на
// неї можуть усі блоки — так само, як на форматування чисел.
// ====================================================================================

package com.kirianov.kiasoulevplus2.tools.paths

import java.io.File

interface CarDataStore {

    /** Перевести сховище на дані конкретного авто. */
    fun useCar(vin: String)

    /**
     * Скопіювати свої файли в [directory] — так, щоб їх можна було віддати іншому
     * телефону.
     */
    fun exportTo(directory: File)

    /**
     * Злити з собою те, що лежить у [directory].
     *
     * ЗЛИТИ, А НЕ ЗАМІНИТИ. Обидва телефони їздили тією самою машиною й бачили різні
     * її частини; узяти чуже замість свого означало б викинути половину науки, а
     * взяти своє замість чужого — не отримати нічого. Правило злиття в кожного
     * сховища власне, бо власні й дані.
     *
     * @return що саме змінилося, для рядка на екрані. Порожньо — нічого не взяли.
     */
    fun mergeFrom(directory: File): String
}
