// ====================================================================================
// ЗАРЯДКА, ПРО ЯКУ ШИНА НЕ ОГОЛОШУЄ (ChargeSense)
//
// Кадр 581 — це кадр БОРТОВОГО ЗАРЯДНОГО. Він говорить рівно тоді, коли працює
// бортове зарядне, тобто на змінному струмі з побутової розетки або колонки Type 1.
// На швидкій зарядці постійним струмом бортове зарядне не бере участі взагалі:
// станція живить батарею напряму, і кадр 581 мовчить усю сесію.
//
// Через це застосунок не побачив початку зарядки на 8 кВт: ознаки заряджання не
// було, облік лишався в стані «авто не заряджається», а зарядку довелося б ловити
// пізніше — пошуком пропущеної, тобто грубіше й із порогами.
//
// ЩО МОЖНА ВЗЯТИ НАТОМІСТЬ. Струм батареї читається з того самого кадру 21 01, що
// й лічильники, і на зарядці він додатний — енергія входить у пакет. Але сам по
// собі додатний струм зарядки не означає: рекуперація виглядає точно так само.
//
// Розрізняє їх ЧАС І РУХ. Рекуперація — це секунди: гальмування скінчилося, і
// струм змінив знак. Зарядка — це десятки хвилин рівного приймання, і авто при
// цьому стоїть. Тому ознака ставиться лише тоді, коли приймання тримається довше
// за будь-яке гальмування, і скидається на першому ж русі.
//
// Ціна помилки несиметрична, і пороги обрані під це. Проґавити зарядку — втратити
// цілу сесію (те, що вже сталося). Вигадати зарядку на ходу — приписати їй
// рекуперацію за поїздку, і саме тому «авто не рухається» тут обов'язкове.
//
// Чистий Kotlin зі своїм станом: перевіряється тестами.
// ====================================================================================

package com.kirianov.kiasoulevplus2.tools.vehicle

class ChargeSense(
    private val minCurrentA: Double = MIN_CURRENT_A,
    private val holdMs: Long = HOLD_MS,
    private val releaseMs: Long = RELEASE_MS,
) {

    /** Відколи струм безперервно входить у батарею. null — не входить. */
    private var takingSinceMs: Long? = null

    /** Відколи приймання припинилося. null — не припинялося. */
    private var idleSinceMs: Long? = null

    private var charging = false

    /**
     * @param currentA струм батареї в домовленості застосунку: додатний — у батарею.
     * @param moving чи авто рухається. Рух знімає ознаку негайно й без розмов.
     * @return чи вважаємо, що авто заряджається.
     */
    fun observe(currentA: Double, moving: Boolean, nowMs: Long): Boolean {
        if (moving) return stop()

        if (currentA >= minCurrentA) {
            idleSinceMs = null
            val since = takingSinceMs ?: nowMs.also { takingSinceMs = it }
            if (nowMs - since >= holdMs) charging = true
            return charging
        }

        // Приймання припинилося. Одразу знімати ознаку не можна: на зарядці струм
        // просідає до нуля і в паузах станції, і при балансуванні наприкінці.
        takingSinceMs = null
        if (!charging) return false
        val idle = idleSinceMs ?: nowMs.also { idleSinceMs = it }
        if (nowMs - idle >= releaseMs) charging = false
        return charging
    }

    /** Розрив зв'язку: усе, що ми знали про струм, застаріло. */
    fun forget() {
        stop()
    }

    private fun stop(): Boolean {
        takingSinceMs = null
        idleSinceMs = null
        charging = false
        return false
    }

    companion object {
        /**
         * Найменший струм, який вважаємо зарядкою, А.
         *
         * Дві ампери — це близько 0.7 кВт, тобто повільніше за найповільнішу
         * побутову розетку. Нижче лежить лише службовий обмін самої батареї.
         */
        const val MIN_CURRENT_A = 2.0

        /**
         * Скільки приймання має триматися безперервно, щоб повірити в зарядку.
         *
         * Три хвилини. Найдовший спуск з гори переривається то газом, то рівною
         * ділянкою, і безперервних трьох хвилин рекуперації не дає; зарядка ж
         * триває годину й більше, тож ці три хвилини коштують часток відсотка
         * сесії — і то лише тих, які й так дораховує пошук пропущеної зарядки.
         */
        const val HOLD_MS = 3 * 60 * 1000L

        /**
         * Скільки чекати, перш ніж вважати зарядку скінченою.
         *
         * П'ять хвилин: станція вміє пригальмовувати, а наприкінці зарядки струм
         * і зовсім падає до одиниць ампер. Рвати сесію на кожній паузі не варто —
         * тим більше, що облік усе одно закриє її, щойно авто ввімкнуть.
         */
        const val RELEASE_MS = 5 * 60 * 1000L
    }
}
