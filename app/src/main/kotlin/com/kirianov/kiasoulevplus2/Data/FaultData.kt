// ====================================================================================
// ПОМИЛКИ БЛОКІВ АВТО (FaultData)
//
// Перше, що робить будь-який діагност, під'єднавшись до машини, — питає блоки, чи
// немає в них помилок. Це і найпростіше з усього, що вміє шина, і найкорисніше:
// код помилки називає несправність прямо, без здогадів про байти.
//
// ЯК ЦЕ ПИТАЄТЬСЯ. Не стандартним OBD (сервіс 03) — на цій машині він мовчить, бо
// відповідає лише блок, що відповідає за викиди, а в електромобіля його немає.
// Питаємо кожен блок окремо його ж заголовком. Тому й список блоків тут: без
// адреси спитати нема кого.
//
// ЗАПИТІВ ДВА, І ЦЕ ПЕРЕВІРКА, А НЕ ПЕРЕСТРАХУВАННЯ. Перший — UDS `19 02 FF`.
// Перше ж опитування живої машини показало, що половина блоків відповідає на нього
// відмовою з родини «такої послуги не знаю»: VCU, батарея, гальма. А батарея при
// цьому чудово відповідає нам на `21 01` — і `21` це служба KWP2000, якої в UDS
// узагалі немає. Отже машина 2015 року швидше говорить по KWP, а помилки в ньому
// питаються командою `18 02 FF 00`, і відповідь починається з `58`.
//
// Тому питаємо обома й беремо ту відповідь, яка щось сказала. Зайвий запит коштує
// долі секунди, а вгадування — ще одного вечора.
//
// СПИСОК БЛОКІВ — ЦЕ ЗДОГАДИ, І ТАК І ЗАПИСАНО. Адреси взяті з того, що відомо про
// Hyundai/Kia тих років; яка з них є в конкретній машині, знає лише сама машина.
// Тому опитуються всі, а показуються ті, що відповіли: мовчання — теж відповідь,
// і чесніше показати його, ніж викреслити блок зі списку назавжди.
// ====================================================================================

package com.kirianov.kiasoulevplus2.Data

/**
 * Один блок авто: чим його питати і як називати людині.
 *
 * [header] — заголовок запиту на шині. Відповідь приходить з іншого, зазвичай на
 * 8 більшого, але ELM327 розбирається з цим сам.
 */
data class Ecu(val header: String, val name: String)

/**
 * Одна помилка.
 *
 * [code] у звичному вигляді — P0562-00, C1611-08. Літера каже, чия це галузь:
 * P — силова частина, C — шасі, B — кузов, U — зв'язок між блоками.
 *
 * [status] — байт стану з UDS. У ньому й лежить головне: помилка активна прямо
 * зараз чи це слід минулого. Без нього список кодів однаково тривожний і для живої
 * несправності, і для тієї, що сталася рік тому й більше не повторювалася.
 */
data class Fault(
    val code: String,
    val status: Int,
) {
    /** Помилку підтверджено: вона траплялася достатньо разів, щоб блок її записав. */
    val confirmed: Boolean get() = status and CONFIRMED != 0

    /** Перевірка провалюється просто зараз — несправність жива. */
    val failingNow: Boolean get() = status and TEST_FAILED != 0

    /** Блок просить засвітити лампу на панелі. */
    val warningLight: Boolean get() = status and WARNING_INDICATOR != 0

    /** Стан людською мовою, найважливіше спереду. */
    val stateText: String
        get() = when {
            failingNow -> "активна зараз"
            confirmed -> "підтверджена, зараз не повторюється"
            else -> "слід у пам'яті"
        }

    private companion object {
        const val TEST_FAILED = 0x01
        const val CONFIRMED = 0x08
        const val WARNING_INDICATOR = 0x80
    }
}

/** Що відповів один блок. */
data class EcuFaults(
    val ecu: Ecu,
    val faults: List<Fault> = emptyList(),

    /**
     * Що сталося, якщо кодів немає.
     *
     * Три різні речі виглядають однаково — «порожньо», — а означають протилежне:
     * блок відповів «помилок немає», блок промовчав (його в цій машині немає), блок
     * відмовив у запиті. Без цього рядка їх не розрізнити.
     */
    val note: String = "",

    /** Чи блок узагалі озвався. Мовчання — це «такого блока тут немає». */
    val answered: Boolean = false,
) {
    val hasFaults: Boolean get() = faults.isNotEmpty()

    val active: Int get() = faults.count { it.failingNow }
}

enum class FaultScanRequest { None, Scan }

/**
 * Сира відповідь одного блока — рівно те, що сказав адаптер.
 *
 * Публікується окремо від розібраного навмисно, як і решта кадрів: шину слухає
 * один блок, а розбирає інший, і про існування одне одного вони не знають.
 *
 * [sequence] тут не прикраса: два блоки цілком можуть відповісти однаково («не
 * відповів»), а для сховища стану однакове значення — не подія. Без номера друга
 * така відповідь просто загубилася б.
 */
data class FaultAnswer(
    val header: String,

    /**
     * Відповіді на кожен із [Ecus.REQUESTS], у тому ж порядку.
     *
     * Список, а не рядок: блок питається двома мовами одразу, і показати треба ту
     * відповідь, яка щось сказала. Яка саме — вирішує розбір, а не шина.
     */
    val raw: List<String>,
    val sequence: Long,
)

data class FaultState(
    val request: FaultScanRequest = FaultScanRequest.None,

    /** Остання сира відповідь: її кладе блок Bluetooth, розбирає блок car/dtc. */
    val answer: FaultAnswer? = null,

    /** Чи опитування триває просто зараз. */
    val running: Boolean = false,

    /** Скільки блоків уже опитано з усього списку. */
    val done: Int = 0,
    val total: Int = 0,

    val results: List<EcuFaults> = emptyList(),

    /** Коли закінчилося останнє опитування. Нуль — ще жодного не було. */
    val scannedAtMs: Long = 0L,
) {
    val answered: List<EcuFaults> get() = results.filter { it.answered }

    val faults: Int get() = results.sumOf { it.faults.size }

    val active: Int get() = results.sumOf { it.active }

    val hasResults: Boolean get() = results.isNotEmpty()
}

/**
 * Кого питаємо.
 *
 * Список навмисно короткий і з відомих: краще опитати вісім блоків за десять
 * секунд, ніж перебирати сотню адрес наосліп. Коли знайдеться ще один — його сюди
 * і додамо, разом із доказом, що він відповідає.
 */
object Ecus {

    /**
     * Запит: «віддай усі свої коди, з будь-яким станом».
     *
     * Служба 19 — читання, а не запис: вона нічого в машині не міняє. Стерти
     * помилки застосунок НЕ вміє й уміти не буде: стерта помилка — це загублена
     * підказка, а не полагоджена машина.
     */
    const val REQUEST = "1902FF"

    /** Те саме по-старому, мовою KWP2000: «віддай коди з будь-яким станом». */
    const val REQUEST_KWP = "1802FF00"

    /**
     * Обидва запити, у порядку опитування.
     *
     * Порядок не випадковий: в UDS код займає три байти замість двох, тобто несе
     * ще й тип відмови. Якщо блок розуміє обидві мови, хочемо саме цю відповідь.
     */
    val REQUESTS = listOf(REQUEST, REQUEST_KWP)

    val ALL = listOf(
        Ecu("7E2", "Керування авто (VCU)"),
        Ecu("7E4", "Батарея (BMS)"),
        // 7E0 у бензинової машини — двигун, і саме тому його тут більше немає:
        // двигуна в цій машині теж немає, і на першому опитуванні адреса
        // промовчала. Мотор з інвертором у Soul EV відгукується на 7E3.
        Ecu("7E3", "Мотор і інвертор"),
        Ecu("7B3", "Клімат"),
        Ecu("7D1", "Гальма (ABS/ESC)"),
        Ecu("7A0", "Тиск у шинах"),
        Ecu("7C6", "Панель приладів"),
        Ecu("7D4", "Підсилювач керма"),
        Ecu("770", "Кузовна електроніка"),
    )
}
