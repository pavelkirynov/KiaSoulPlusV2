package com.kirianov.kiasoulevplus2.Data

/**
 * ЩО ЗА АВТО ПЕРЕД НАМИ.
 *
 * З'явилося тоді, коли застосунок перестав бути «моїм на моїй машині». Доти все,
 * що він знав про авто, було константами в коді: шістнадцять комірок CATL,
 * 50.88 кВт·год. Це чесно описувало одну конкретну машину — і ставало небезпечним
 * у першу ж мить, коли APK потрапляв до іншої людини. На стоковому Soul EV з
 * рідними 27 кВт·год такий застосунок упевнено обіцяв би вдвічі більший запас, і
 * людина поїхала б за цією цифрою.
 *
 * [vin] — те єдине на шині, що відповідає на питання «а це та сама машина». Без
 * нього телефон, підключившись до чужого авто, спокійно домішав би його поїздки до
 * чужої моделі й зіпсував би обидві.
 */
data class CarProfile(
    val vin: String = "",

    /** Як водій назвав авто. Порожньо — покажемо хвіст VIN. */
    val name: String = "",

    /**
     * Корисна ємність пакета, кВт·год. Нуль означає «ще не питали».
     *
     * Вивести це число з чогось на шині неможливо: BMS рахує відсотки за паспортом
     * РІДНОГО пакета й про заміну не знає — саме тому шкала на перепакованій
     * батареї й виходить нерівною. Знає про заміну лише той, хто її робив.
     */
    val packKwh: Double = 0.0,

    /** Коли це авто бачили востаннє. За ним впорядковується список. */
    val lastSeenAtMs: Long = 0L,
) {
    /**
     * Ємність, з якою рахувати просто зараз.
     *
     * Обережність однобока навмисно: поки ємність не задано, беремо РІДНИЙ пакет, а
     * не перепакований. Занизити запас ходу означає, що людина зайвий раз
     * зарядиться; завищити — що вона стане на дорозі.
     */
    val effectivePackKwh: Double
        get() = if (packKwh > 0.0) packKwh else Pack.ORIGINAL_CAPACITY_KWH

    val packKnown: Boolean get() = packKwh > 0.0

    val known: Boolean get() = vin.isNotEmpty()
}

/**
 * Усі авто, про які застосунок щось знає, і те, за яке він рахує зараз.
 *
 * [detectedVin] — що прочитали з шини в цьому підключенні; [activeVin] — за яке
 * авто ведеться облік. Зазвичай це те саме, але не завжди: коли зв'язку немає,
 * водій може обрати авто вручну, щоб подивитися вже накопичене.
 */
data class Garage(
    val cars: List<CarProfile> = emptyList(),
    val activeVin: String = "",
    val detectedVin: String = "",

    /** Обмін даними авто між телефонами. Не зберігається: живе одну дію. */
    val share: ShareState = ShareState(),

    /** Чи прочитано список із диска. До того типові значення — не вибір користувача. */
    val loaded: Boolean = false,
) {
    val active: CarProfile
        get() = cars.firstOrNull { it.vin == activeVin } ?: CarProfile(vin = activeVin)

    /** Чи авто на шині — те саме, за яке ми рахуємо. */
    val mismatched: Boolean
        get() = detectedVin.isNotEmpty() && activeVin.isNotEmpty() && detectedVin != activeVin
}

/** Що екран просить зробити з обміном. */
enum class ShareRequest { None, Export, Import }

/**
 * Обмін даними одного авто між телефонами.
 *
 * Одна машина, два водії, два телефони: кожен бачить свою половину поїздок, і жодна
 * з половин сама по собі не дає повної картини. Сервера в застосунку немає, а от
 * файл переслати вміє будь-хто.
 *
 * [exportedPath] — готовий файл, який екран має віддати системі «поділитися»;
 * [importPath] — файл, який людина обрала, і його треба прийняти. Обидва
 * порожніють одразу після того, як їх обробили: це доручення, а не стан.
 */
data class ShareState(
    val request: ShareRequest = ShareRequest.None,
    val exportedPath: String = "",
    val importPath: String = "",

    /** Що вийшло, людською мовою. Показується на екрані налаштувань. */
    val note: String = "",
)
