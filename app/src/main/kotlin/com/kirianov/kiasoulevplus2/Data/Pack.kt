package com.kirianov.kiasoulevplus2.Data

/**
 * ЩО ЗА БАТАРЕЯ СТОЇТЬ У ЦЬОМУ АВТО.
 *
 * Кузов і привід — Soul EV 2015. Батарея замінена: **16 комірок CATL по
 * 3.18 кВт·год, хімія NMC**, разом 50.8 кВт·год проти рідних 27. Вимір зарядкою
 * підтвердив цю цифру й навіть трохи більше.
 *
 * НАСЛІДКИ, І ЇХ ДВА — РІЗНІ ЗА ПРИРОДОЮ.
 *
 * 1. МАСШТАБ. За кожним відсотком шкали стоїть майже вдвічі більше кіловат-годин,
 *    ніж рахує BMS: вона рахує за паспортом рідних комірок.
 *
 * 2. ФОРМА, і це важливіше. Хімія інша, тобто інший діапазон напруг на комірку.
 *    BMS накладає заводську таблицю «напруга → відсоток» на криву, для якої вона
 *    не робилася, — і шкала виходить різко НЕРІВНОЮ. За спостереженням водія:
 *
 *        від 100 %   відсоток коштує близько 1 км
 *        посередині  близько 2 км
 *        у кінці     від 5 до 10 км
 *
 *    Тобто нахил гуляє в рази. Через це будь-який місцевий вимір — «на ділянці
 *    88–95 % вийшло 0.29 кВт·год на відсоток» — НЕ можна розтягувати на всю
 *    шкалу: угорі відсоток найдешевший, і з такого розтягування виходило
 *    29 кВт·год замість справжніх п'ятдесяти.
 *
 * Тому повна ємність і форма шкали міряються ОКРЕМО. Повна ємність — аксіома з
 * цих даних, яку уточнює зарядка з низьких відсотків; форма — заміри по ділянках.
 *
 * Ще дві особливості експлуатації, які варто пам'ятати: заряд іде не до кінця
 * (4.12 В на комірку), а повний розряд до відключення не перевірявся. Тобто
 * «сто відсотків» і «нуль» тут — це робоче вікно, а не фізичні межі пакета.
 *
 * Константи живуть у Data, бо це не модель і не логіка, а факт про машину, який
 * потрібен кільком блокам одразу.
 */
object Pack {

    /** Скільки комірок і по скільки кВт·год у них. */
    const val CELLS = 16
    const val CELL_KWH = 3.18

    /**
     * Повна корисна ємність, кВт·год: аксіома для старту розрахунків.
     *
     * Уточнюється виміром із зарядки, що починалася з низьких відсотків (1–4 %):
     * лічильник прийнятої енергії веде сама батарея, тож у тому вимірі немає
     * втрат бортового зарядного — на відміну від показів розетки.
     */
    const val USABLE_CAPACITY_KWH = CELLS * CELL_KWH

    /**
     * Рідний пакет, за паспортом якого досі рахує BMS. Потрібен лише для одного:
     * показати, у скільки разів перепаковка більша за те, від чого відштовхується
     * приладова панель.
     */
    const val ORIGINAL_CAPACITY_KWH = 27.0

    /** Скільки комірок у ланцюжку. Потрібно, щоб показувати вольти на комірку. */
    const val CELLS_IN_SERIES = 96

    /**
     * Найбільший струм розряду, А: приблизно те, що бере мотор на повній
     * потужності (81 кВт при ~360 В). Від нього рахується «навантаження у
     * відсотках» для кривої напруги.
     */
    const val MAX_CURRENT_A = 230.0
}
