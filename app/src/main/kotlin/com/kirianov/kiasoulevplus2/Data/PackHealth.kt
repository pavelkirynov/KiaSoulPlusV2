// ====================================================================================
// ЩО БАТАРЕЯ ДУМАЄ ПРО СЕБЕ САМА (PackHealth)
//
// Кадр 21 01, який застосунок читає щосекунди, каже, що з батареєю ЗАРАЗ. Кадр
// 21 05 каже інше — що з нею СТАЛОСЯ: скільки, на думку BMS, зносилися комірки, і
// які з них найгірші.
//
// ЧОМУ ЦЕ ВАЖЛИВО САМЕ НА ЦІЙ МАШИНІ. Усі наші висновки про пакет досі спиралися
// на один прилад — власні заміри під навантаженням. Деградація з BMS — прилад
// другий і незалежний, і саме розбіжність між ними варта уваги. Абсолютне число
// тут під підозрою: BMS рахує його проти РІДНОЇ хімії, як і відсотки заряду. А от
// РОЗКИД між найгіршою й найкращою коміркою від паспорта не залежить: він каже,
// чи розходяться комірки на думку самої батареї.
//
// ТЕМПЕРАТУРИ ТУТ СПРАВЖНІ МАКСИМУМ І МІНІМУМ по пакету — на відміну від байта 16
// кадру 21 01, який виявився температурою першого модуля.
// ====================================================================================

package com.kirianov.kiasoulevplus2.Data

/**
 * Знімок кадру 21 05.
 *
 * [known] хибне, поки кадр не прийшов: усі нулі тут неможливо відрізнити від
 * справжніх нулів, а нуль градусів і нульова деградація — цілком законні числа.
 */
data class PackHealth(
    val known: Boolean = false,

    /** Найвища й найнижча температура модулів по всьому пакету, °C. */
    val maxTempC: Double = 0.0,
    val minTempC: Double = 0.0,

    /** Температура на вході контуру охолодження, °C. */
    val inletTempC: Double = 0.0,

    /** Температури двох нагрівачів батареї, °C. */
    val heater1TempC: Double = 0.0,
    val heater2TempC: Double = 0.0,

    /**
     * Деградація найгіршої та найкращої комірки за версією BMS, %, і їхні номери.
     *
     * Сто відсотків означає «як нова». Дивитися варто на РІЗНИЦЮ між цими двома:
     * абсолютне число BMS рахує проти рідної хімії, а розкид — просто розкид.
     */
    val maxDeteriorationPercent: Double = 0.0,
    val maxDeteriorationCell: Int = 0,
    val minDeteriorationPercent: Double = 0.0,
    val minDeteriorationCell: Int = 0,

    /** Той самий SOC, що на панелі приладів, — для звірки з рештою джерел. */
    val displaySoc: Double = 0.0,
) {
    /** Наскільки розійшлися комірки за зносом, відсоткових пунктів. */
    val deteriorationSpread: Double
        get() = maxDeteriorationPercent - minDeteriorationPercent

    /** Розкид температур по пакету, °C: за ним видно, чи є перегрітий бік. */
    val tempSpreadC: Double get() = maxTempC - minTempC
}
