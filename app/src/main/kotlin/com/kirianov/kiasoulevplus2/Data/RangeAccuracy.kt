package com.kirianov.kiasoulevplus2.Data

import kotlin.math.abs

/**
 * Чи стримав прогноз обіцянку.
 *
 * ЩО САМЕ ТУТ МІРЯЄТЬСЯ. На початку поїздки застосунок сказав «200 км». Проїхали
 * 50, а він каже вже «135». Отже 50 км дороги з'їли 65 км запасу — початкова
 * оцінка була оптимістична на 30 %. Якби прогноз був точний, запас падав би
 * рівно на стільько, скільки проїхано.
 *
 * ЧОМУ ЦЕ, А НЕ ВЛАСНИЙ ПІДРАХУНОК ШЛЯХУ. Спершу тут стояв інтеграл швидкості
 * проти одометра. Але швидкість і одометр приходять ОДНИМ кадром 4F0: якщо є
 * швидкість, є й одометр, тож підмінити його інтегралом ніколи не доведеться.
 * Той підрахунок міряв точність арифметики, яка нікому не потрібна. Це — міряє
 * помилку самої моделі, тобто те, заради чого застосунок і зроблений.
 *
 * ВІДЛІК ПОЧИНАЄТЬСЯ НЕ З ПЕРШОГО ЧИСЛА, А З ПЕРШОГО УСТОЯНОГО, і це виправлення
 * помилки, яку видно було на екрані щоразу. Перший прогноз після під'єднання
 * приходить занижений — модель ще не має ні свіжого точного SOC (кадр 598 стоїть
 * у черзі раз на ~45 с), ні умов цієї поїздки, — і через сотню метрів
 * перераховується вгору. На знімку екрана це виглядало так: «обіцяв на початку
 * 245, обіцяє зараз 261, проїхали 0.1 км», тобто шістнадцять кілометрів помилки
 * з'явилися рівно з нічого.
 *
 * Тому тепер відлік прив'язується до першого прогнозу, який ПІДТВЕРДИВ СЕБЕ:
 * наступне читання відрізняється від попереднього менше ніж на [SETTLE_TOLERANCE].
 * Чекати за кілометрами (як напрошується) гірше: на 60 км/год кілометр — це
 * шістдесят секунд, а прогноз може встоятися за десять або не встоятися за сто.
 * Умова тут та сама, що й у самому питанні: «прогноз перестав стрибати».
 */
data class RangeAccuracy(
    /** Що обіцяв прогноз на початку відліку, км. */
    val startRangeKm: Double = 0.0,

    /** Що обіцяє зараз, км. */
    val currentRangeKm: Double = 0.0,

    /** Скільки проїхано за одометром від початку відліку, км. */
    val drivenKm: Double = 0.0,

    /**
     * Одометр на початку відліку, км.
     *
     * Не private, хоч і внутрішня величина: без неї відлік неможливо підняти з
     * файлу, а він мусить переживати перезапуск — інакше кожне оновлення
     * застосунку починає перевірку прогнозу з нуля.
     */
    val startOdometerKm: Double = 0.0,
    val started: Boolean = false,

    /**
     * Останній побачений прогноз, поки відлік ще не прив'язаний.
     *
     * У файл не пишеться навмисно: це стан очікування, який коштує двох читань
     * шини. Після перезапуску дешевше почекати ще раз, ніж піднімати з диска
     * напівстан і гадати, чи він досі про цю поїздку.
     */
    val pendingRangeKm: Double = 0.0,
) {
    /** На скільки впав обіцяний запас. */
    val predictedDropKm: Double get() = startRangeKm - currentRangeKm

    /**
     * Наскільки запас падав швидше за дорогу. Додатне означає оптимістичний
     * прогноз: обіцяного не проїдеш.
     */
    val errorKm: Double get() = predictedDropKm - drivenKm

    /** Та сама помилка у відсотках від пройденого. */
    val errorPercent: Double?
        get() = if (hasEnoughDistance) errorKm / drivenKm * 100.0 else null

    /**
     * Поки не набралося кілометрів, відсоток нічого не означає: на першому
     * кілометрі похибка одометра в 0.1 км дає вже 10 %.
     */
    val hasEnoughDistance: Boolean get() = started && drivenKm >= MIN_DISTANCE_KM

    /**
     * Починає відлік. Потрібні обидва числа одразу: прогноз без одометра нема з
     * чим порівнювати, одометр без прогнозу — нема що перевіряти.
     */
    fun startedAt(rangeKm: Double, odometerKm: Double): RangeAccuracy =
        if (rangeKm <= 0.0 || odometerKm <= 0.0) {
            this
        } else {
            RangeAccuracy(
                startRangeKm = rangeKm,
                currentRangeKm = rangeKm,
                startOdometerKm = odometerKm,
                started = true,
            )
        }

    fun observe(rangeKm: Double, odometerKm: Double): RangeAccuracy {
        if (rangeKm <= 0.0 || odometerKm <= 0.0) return this
        if (!started) return waitUntilSettled(rangeKm, odometerKm)

        return copy(
            currentRangeKm = rangeKm,
            // Одометр не може йти назад; якщо пішов — це хибне читання, не від'ємний шлях.
            drivenKm = (odometerKm - startOdometerKm).coerceAtLeast(0.0),
        )
    }

    /**
     * Чекає, поки прогноз підтвердить сам себе, і лише тоді прив'язує відлік.
     *
     * Перше читання нічого не вирішує: його просто нема з чим порівняти. Друге
     * або підтверджує перше — і тоді відлік починається від НЬОГО, а не від
     * першого, — або ні, і тоді воно саме стає тим, що треба підтвердити.
     */
    private fun waitUntilSettled(rangeKm: Double, odometerKm: Double): RangeAccuracy {
        val previous = pendingRangeKm
        if (previous <= 0.0) return copy(pendingRangeKm = rangeKm)

        val settled = abs(rangeKm - previous) <= previous * SETTLE_TOLERANCE
        return if (settled) startedAt(rangeKm, odometerKm) else copy(pendingRangeKm = rangeKm)
    }

    /** Чи відлік уже чекає на устояний прогноз, а не просто порожній. */
    val waitingToSettle: Boolean get() = !started && pendingRangeKm > 0.0

    companion object {
        /** Менше цього відсоток помилки — це шум одометра, а не якість прогнозу. */
        const val MIN_DISTANCE_KM = 3.0

        /**
         * Наскільки два прогнози підряд можуть різнитися, щоб вважати другий
         * устояним. Частка, не відсотки.
         *
         * Два відсотки — це кілька кілометрів із двохсот п'ятдесяти, тобто менше
         * за крок самого прогнозу. Перший стрибок, який ми ловимо, був у шість
         * разів більший: 245 на 261.
         */
        const val SETTLE_TOLERANCE = 0.02
    }
}
