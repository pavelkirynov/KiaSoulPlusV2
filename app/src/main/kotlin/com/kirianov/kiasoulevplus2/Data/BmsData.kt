package com.kirianov.kiasoulevplus2.Data

/**
 * Показники високовольтної батареї, зчитані з кадру BMS 21 01.
 * displaySoc = -1.0 означає «даних ще немає», щоб відрізнити це від справжнього нуля.
 */
data class BmsData(
    val displaySoc: Double = NO_DATA,     // SOC з BMS (%)
    val batteryVoltage: Double = 0.0,     // Напруга батареї (В)
    // Струм (А), від'ємний = розряд. Сире значення з BMS протилежне за знаком —
    // див. пояснення в BmsResponseDecoder.
    val batteryCurrent: Double = 0.0,
    /**
     * Температура ПЕРШОГО модуля, °C — байт 16 кадру 21 01.
     *
     * Раніше поле називалося «максимальна температура модулів», і це було
     * неправильно: байт 16 — початок списку восьми модулів ([moduleTempsC]).
     * Справжні максимум і мінімум по пакету приходять іншим кадром, 21 05, і
     * живуть у [PackHealth].
     */
    val batteryTempC: Double = 0.0,

    /**
     * Лічильники енергії за весь час життя батареї (кВт·год).
     * Самі по собі це великі числа; корисна з них саме різниця за поїздку.
     */
    val cumulativeEnergyChargedKwh: Double = 0.0,
    val cumulativeEnergyDischargedKwh: Double = 0.0,

    /**
     * Ті самі лічильники, але в амперу-годинах. Показуються поруч із кВт·год
     * навмисно: їх відношення мусить дати середню напругу пакета, і саме ця
     * перехресна перевірка викриває читання не тих байтів. Раніше як кВт·год
     * показувалися саме ці числа.
     */
    val cumulativeChargedAh: Double = 0.0,
    val cumulativeDischargedAh: Double = 0.0,

    // --- Те, що лежало в тому самому кадрі й досі викидалося ------------------
    //
    // Кадр 21 01 приходить кожен опрок і містить п'ятдесят сім байтів, з яких
    // застосунок читав вісім полів. Решта — не «додаткові запити», а байти, які
    // вже в руках: жодного зайвого звернення до шини нижче немає.

    /**
     * Скільки батарея дозволяє БРАТИ просто зараз, кВт.
     *
     * Це не наша оцінка, а межа, яку BMS сама виставляє інвертору. Вона падає на
     * морозі й на низькому заряді — і саме тому машина «не тягне» в певних умовах.
     */
    val availableDischargeKw: Double = 0.0,

    /**
     * Скільки батарея дозволяє ВЛИВАТИ просто зараз, кВт.
     *
     * Ця межа й керує тим, як швидка зарядка знижує струм ближче до сотні: не
     * станція вирішує, а батарея.
     */
    val availableChargeKw: Double = 0.0,

    /** BMS каже, що заряджається просто зараз. */
    val bmsCharging: Boolean = false,

    /** Уставлений роз'єм: швидкий CHAdeMO та/або звичайний Type 1. */
    val chademoPlugged: Boolean = false,
    val j1772Plugged: Boolean = false,

    /**
     * Температури ВОСЬМИ модулів окремо, °C.
     *
     * Для перепакованої батареї це найкорисніше з усього списку: видно, який бік
     * пакета гріється, а одне число «максимум» цього не каже.
     */
    val moduleTempsC: List<Double> = emptyList(),

    /** Найвища й найнижча напруга комірки за версією BMS, В, та їхні номери. */
    val maxCellVolts: Double = 0.0,
    val maxCellNumber: Int = 0,
    val minCellVolts: Double = 0.0,
    val minCellNumber: Int = 0,

    /** Обороти вентилятора охолодження, 0-9, і його зворотний сигнал, Гц. */
    val fanStep: Int = 0,
    val fanHz: Int = 0,

    /**
     * Напруга допоміжного 12-вольтового акумулятора, В.
     *
     * Найчастіша причина «машина не запускається» в електромобілі — саме він, а
     * не тяговий пакет. Число тут дармове, а попереджає про справжню поломку.
     */
    val auxVolts: Double = 0.0,

    /** Скільки батарея відпрацювала за весь час, секунд. */
    val operatingSeconds: Long = 0L,

    /** Обороти тягового мотора, об/хв. */
    val motorRpm: Int = 0,
) {
    val hasData: Boolean get() = displaySoc >= 0.0

    /** Години роботи батареї — так це число читається людиною. */
    val operatingHours: Double get() = operatingSeconds / 3600.0

    /** Чи вдалося зчитати лічильники: кадр буває коротшим, ніж місце, де вони лежать. */
    val hasEnergyCounters: Boolean get() = cumulativeEnergyDischargedKwh > 0.0

    companion object {
        const val NO_DATA = -1.0
    }
}
