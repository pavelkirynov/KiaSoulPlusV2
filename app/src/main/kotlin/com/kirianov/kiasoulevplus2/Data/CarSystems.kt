// ====================================================================================
// СИСТЕМИ АВТО ПОЗА БАТАРЕЄЮ (CarSystems)
//
// Усе, що знайшлося у вихідниках SoulEVSpy і чого в нас досі не було: колеса,
// ручник, світло зі склоочисниками, годинник магнітоли й окремий кадр швидкості з
// бітом запалювання. Це широкомовні кадри — авто говорить їх само, без запиту.
//
// ЧОМУ ОКРЕМО ВІД VehicleData. Там лежить те, на чому стоять розрахунки: пробіг,
// SOC, запас ходу. Тут — те, що ЩЕ ПЕРЕВІРЯЄТЬСЯ. Числа взяті з чужої програми,
// писаної під РІДНУ батарею 27 кВт·год, і вже один раз підвели: їхня формула
// швидкості з кадру 4F2 дає 128 км/год на місці, бо в старший біт складено
// запалювання. Тримати неперевірене поруч із тим, що живить прогноз, означало б
// одного дня побудувати прогноз на здогаді.
//
// КОЖНА ПІДСИСТЕМА МАЄ ВЛАСНЕ `known`. Нуль тут — законне значення: нуль км/год,
// вимкнене світло, нульова секунда. Відрізнити «кадр не приходив» від «прийшов і
// там нуль» можна лише окремим прапорцем, і саме ця різниця й є відповідь на
// питання «що з цього працює».
// ====================================================================================

package com.kirianov.kiasoulevplus2.Data

/** Знімок усіх систем авто, які застосунок уміє читати з шини. */
data class CarSystems(
    /** Кадр 4B0: чотири колеса окремо. */
    val wheels: WheelSpeeds = WheelSpeeds(),

    /** Кадр 433: ручник. */
    val brake: BrakeState = BrakeState(),

    /** Кадр 050: світло, склоочисники, поворотники. */
    val cabin: CabinControls = CabinControls(),

    /** Кадр 567: годинник магнітоли. */
    val clock: CarClock = CarClock(),

    /** Кадр 4F2: швидкість і запалювання. */
    val drive: DriveState = DriveState(),
) {
    /** Чи прийшов хоч один із нових кадрів: інакше екран нічого не має показувати. */
    val anyKnown: Boolean
        get() = wheels.known || brake.known || cabin.known || clock.known || drive.known
}

/**
 * Швидкість обертання кожного колеса, км/год. Кадр 4B0, по два байти на колесо,
 * молодший перший, поділити на 30.
 *
 * НАВІЩО ЦЕ НАМ. Не для швидкості — її дає кадр 4F0. Для двох інших речей:
 * по-перше, [spreadKmh] у повороті мусить рости, а на прямій — ні, і це готова
 * перевірка, що байти прочитані правильно; по-друге, за словами SoulEVSpy цей
 * кадр приходить навіть із вимкненим запалюванням, тобто ним можна побачити рух
 * буксирування чи скочування.
 */
data class WheelSpeeds(
    val known: Boolean = false,
    val frontLeftKmh: Double = 0.0,
    val frontRightKmh: Double = 0.0,
    val rearLeftKmh: Double = 0.0,
    val rearRightKmh: Double = 0.0,
) {
    val all: List<Double> get() = listOf(frontLeftKmh, frontRightKmh, rearLeftKmh, rearRightKmh)

    val averageKmh: Double get() = all.average()

    /** Розбіг між найшвидшим і найповільнішим колесом, км/год. */
    val spreadKmh: Double get() = all.max() - all.min()
}

/** Ручник. Кадр 433, байт 2, біт 3. */
data class BrakeState(
    val known: Boolean = false,
    val parkingBrakeOn: Boolean = false,
)

/**
 * Світло, склоочисники й поворотники. Кадр 050, байти 1 і 2.
 *
 * Кадр стоїть у черзі прослуховування раз на цикл, тобто раз на кілька хвилин.
 * Це навмисно: як ЖИВИЙ покажчик поворотника воно все одно не годиться, а як
 * відповідь на «чи є в цій машині такий кадр і чи так у ньому розкладені біти» —
 * годиться цілком.
 */
data class CabinControls(
    val known: Boolean = false,
    val lights: LightsMode = LightsMode.Off,
    val turnSignal: TurnSignal = TurnSignal.Off,
    val wipers: WiperSpeed = WiperSpeed.Off,

    /**
     * Щабель перебійного режиму склоочисників, 0-4, де 0 найповільніший.
     *
     * Має сенс лише при [WiperSpeed.Intermittent]: у решті режимів ті самі біти
     * означають інше.
     */
    val wiperStep: Int = 0,
)

enum class LightsMode { Off, Parking, On, Automatic }

enum class TurnSignal { Off, Left, Right }

enum class WiperSpeed { Off, Intermittent, Normal, Fast }

/**
 * Годинник магнітоли. Кадр 567, байти 1-3 — години, хвилини, секунди.
 *
 * ЗА ДЖЕРЕЛО ЧАСУ ЦЕ ВЖЕ ВІДКИНУТО: магнітола йде як їй заманеться, і діагностику
 * дрейфу ми з застосунку прибрали. Лишається як ознака, що кадр читається
 * правильно: секунди мусять рахувати одна за одною, і жодне інше поле в наших
 * кадрах не перевіряється так дешево.
 */
data class CarClock(
    val known: Boolean = false,
    val hour: Int = 0,
    val minute: Int = 0,
    val second: Int = 0,
) {
    val text: String
        get() = listOf(hour, minute, second).joinToString(":") { it.toString().padStart(2, '0') }
}

/**
 * Кадр 4F2: швидкість і запалювання.
 *
 * ТУТ ЖИВЕ НАША ЄДИНА ПОПРАВКА ДО SoulEVSpy. Їхня формула складає в швидкість
 * старший біт байта 2 — і на цій машині це не швидкість, а ЗАПАЛЮВАННЯ: на місці
 * з увімкненим запалюванням вона дає рівно 128 км/год. Ми читаємо швидкість самим
 * байтом 1, а біти байта 2 — як запалювання, і кожне з двох чисел тепер можна
 * перевірити окремо: швидкість — проти кадру 4F0, запалювання — проти того, що
 * дев'ять кадрів шини існують лише при ньому.
 */
data class DriveState(
    val known: Boolean = false,

    /** Байт 1, поділений на два: 0-127.5 км/год. */
    val speedKmh: Double = 0.0,

    /** Байт 2, біти 6-7. */
    val ignitionOn: Boolean = false,
)
