package com.kirianov.kiasoulevplus2.Data

/**
 * Показники, які авто транслює широкомовними кадрами, а не віддає на запит.
 *
 * Кожне поле має власну познаку «немає даних»: у одному вікні монітора приходять
 * не всі кадри, тому нові дані домішуються до попередніх, а не замінюють їх цілком.
 */
data class VehicleData(
    /** Пробіг, км. Кадр 4F0, роздільність 0.1 км. */
    val odometerKm: Double = 0.0,

    /** Швидкість, км/год. Кадр 4F0. */
    val speedKmh: Double = NO_DATA,

    /** SOC як на панелі, %. Кадр 594. */
    val displaySocPercent: Double = NO_DATA,

    /** SOC точний, з BMS, %. Кадр 598. Різниця з панельним показує буфери батареї. */
    val preciseSocPercent: Double = NO_DATA,

    /** Залишок ходу за бортовим компьютером, км. Кадр 200. */
    val rangeKm: Int = 0,

    /**
     * Наскільки виріс би запас ходу з вимкненим кліматом, км. Кадр 200, байт 0.
     *
     * Це єдине пряме свідчення про клімат, яке взагалі є на шині: стану печки чи
     * кондиціонера авто не передає, а тут воно саме каже, у скільки кілометрів
     * обходиться клімат просто зараз. Для моделі витрати це набагато краще за
     * здогад із температури за бортом — вона показує погоду, а не те, чи ввімкнена
     * пічка.
     */
    val climateExtraKm: Double = NO_DATA,

    /** Температура за бортом, °C. Кадр 653. Власна познака: −40 °C теж дійсне значення. */
    val ambientTempC: Double = NO_TEMPERATURE,

    /** Стан заряджання. Кадр 581. */
    val charging: ChargingState = ChargingState(),
) {
    val hasOdometer: Boolean get() = odometerKm > 0.0
    val hasSpeed: Boolean get() = speedKmh >= 0.0
    val hasDisplaySoc: Boolean get() = displaySocPercent >= 0.0
    val hasPreciseSoc: Boolean get() = preciseSocPercent >= 0.0
    val hasRange: Boolean get() = rangeKm > 0
    val hasClimateExtra: Boolean get() = climateExtraKm >= 0.0
    val hasAmbientTemp: Boolean get() = ambientTempC > NO_TEMPERATURE

    companion object {
        const val NO_DATA = -1.0

        /** Нижче будь-якої реальної температури: кадр 653 дає від −40 до +87.5 °C. */
        const val NO_TEMPERATURE = -1000.0
    }
}

enum class ChargerType { None, Type1, J1772 }

/**
 * Чи заряджається авто — і звідки ми це знаємо.
 *
 * ТРИ ДЖЕРЕЛА, І ВСІ НАРІЗНО, бо кожне бачить своє й бреше по-своєму.
 *
 * [reported] приходить кадром 581, тобто від БОРТОВОГО ЗАРЯДНОГО: він каже правду
 * про змінний струм і мовчить усю швидку зарядку, бо на постійному струмі станція
 * живить батарею повз нього.
 *
 * [sensed] — наш власний висновок зі струму батареї: довге рівне приймання на
 * місці. Він ловить швидку зарядку, але за означенням запізнюється на хвилини й
 * плутається з рекуперацією, тому й вимагає нерухомості.
 *
 * [plugged] і [bmsSaysCharging] — НАЙКРАЩЕ З ТРЬОХ, і з'явилися останніми: обидва
 * лежать у кадрі 21 01, який читається щосекунди, обидва працюють і на змінному,
 * і на постійному струмі. «Роз'єм уставлений» — це та сама подія, яку бачить
 * людина, коли вставляє пістолет, і вона не потребує ні порогів, ні витримки.
 * Перша ж перевірка на живій зарядці дала `Type 1 = так` разом із «BMS каже
 * заряджаюсь», а межа прийому впала з 90 до 69 кВт.
 *
 * Тримати все це в одному полі не можна: кадр 581 приходить регулярно й затирав
 * би висновок, а висновок затирав би кадр.
 */
data class ChargingState(
    /** Що каже кадр 581 бортового зарядного. */
    val reported: Boolean = false,

    /** Що видно зі струму батареї: довге рівне приймання на місці. */
    val sensed: Boolean = false,

    /** Чи вставлений роз'єм — CHAdeMO або Type 1. Кадр 21 01, байт 11. */
    val plugged: Boolean = false,

    /** Чи каже сама BMS, що заряджається. Той самий байт 11. */
    val bmsSaysCharging: Boolean = false,

    val chargerType: ChargerType = ChargerType.None,
    val powerKw: Double = 0.0,
) {
    /**
     * Уставлений роз'єм ПЛЮС власне слово BMS. Одного роз'єму мало: пістолет
     * буває вставленим і після того, як зарядка скінчилася, — саме так авто й
     * стоїть до ранку.
     */
    val plugCharging: Boolean get() = plugged && bmsSaysCharging

    val isCharging: Boolean get() = reported || sensed || plugCharging
}
