// ====================================================================================
// ЯК КОМІРКИ ЛЕЖАТЬ У ПАКЕТІ (CellLayout)
//
// Номер комірки на шині — це порядок опитування, а не місце в батареї. Усередині
// блока комірки йдуть двома збірками: перша згори вниз, друга навпаки, знизу вгору.
// Тому підряд намальовані номери нічого не кажуть про те, яка комірка зверху, а яка
// знизу, — а бачити треба саме це: просідає й гріється завжди той бік, де гірше з
// охолодженням.
//
// Отже кожен блок ділиться навпіл, і друга половина розвертається:
//
//     блок 1   1  2  3  4  5  6  7        блок 2  15 16 17 18 19
//             14 13 12 11 10  9  8                24 23 22 21 20
//
// Ліворуч виходить верх стопки, праворуч — низ. Номери на екрані лишаються саме
// тому, що порядок тепер не очевидний: без них рядок неможливо звірити з пакетом.
//
// Живе в Data, а не в екрані: це опис самої батареї, а не спосіб її намалювати, і
// перевіряється тестами.
// ====================================================================================

package com.kirianov.kiasoulevplus2.Data

/** Один блок ВВБ: із якої комірки починається і скільки їх у ньому. */
data class CellBlock(val startIndex: Int, val count: Int)

object CellLayout {

    /** Реальна розбивка батареї Kia Soul EV на блоки: 14, 10, 10, 14 — і ще раз. */
    val blocks = listOf(
        CellBlock(0, 14), CellBlock(14, 10), CellBlock(24, 10), CellBlock(34, 14),
        CellBlock(48, 14), CellBlock(62, 10), CellBlock(72, 10), CellBlock(82, 14),
    )

    /**
     * Два ряди блока: перша збірка як є, друга розвернута.
     *
     * Індекси нульові, як на шині; на екран вони виходять із одиницею.
     */
    fun runsOf(block: CellBlock): List<List<Int>> {
        val half = block.count / 2
        return listOf(
            (0 until half).map { block.startIndex + it },
            (half until block.count).map { block.startIndex + it }.reversed(),
        )
    }

    /** Усі ряди підряд, згори вниз, — так вони й малюються. */
    fun rows(): List<List<Int>> = blocks.flatMap { runsOf(it) }

    /**
     * Розкладка «блоки 6s»: як модулі стоять під підлогою насправді.
     *
     * Дев'яносто шість комірок — це шістнадцять модулів по шість, і лежать вони
     * двома рядами по вісім. Лівий ряд іде згори вниз, правий — знизу вгору, тобто
     * нумерація змійкою обходить пакет по колу. Саме тому цю розкладку не можна
     * вивести з номерів: підряд намальована сітка показала б праву половину
     * догори дриґом.
     *
     *     ліва колонка          права колонка
     *     блок 1  (комірки 1-6)      блок 16 (91-96)
     *     блок 2  (7-12)             блок 15 (85-90)
     *       …                          …
     *     блок 8  (43-48)            блок 9  (49-54)
     *
     * Повертає рядки по два блоки: [ліва, права]. Усередині лівого блока комірки
     * ідуть у порядку опитування, у правому — навпаки, щоб змійка не рвалася.
     */
    fun sixCellRows(): List<List<List<Int>>> {
        val left = (0 until HALF_BLOCKS).map { row ->
            val start = row * SIX
            (start until start + SIX).toList()
        }
        val right = (0 until HALF_BLOCKS).map { row ->
            // Правий ряд читається знизу вгору: перший його блок — останній у
            // пакеті, і всередині він теж розвернутий.
            val start = (BLOCKS_6S - 1 - row) * SIX
            (start until start + SIX).toList().reversed()
        }
        return left.indices.map { listOf(left[it], right[it]) }
    }

    /** Скільки комірок в одному модулі розкладки 6s. */
    const val SIX = 6

    /** Скільки таких модулів у пакеті. */
    const val BLOCKS_6S = 16

    private const val HALF_BLOCKS = BLOCKS_6S / 2
}
