// ====================================================================================
// ВПІЗНАННЯ АВТО ЗА НЕПЕРЕРВНІСТЮ (CarIdentity)
//
// Другий свідок особи авто, окрім VIN. VIN на цій машині часто мовчить (віддається
// лише при ввімкненому запаленні), і з кількома авто в гаражі застосунок через це
// не знає, чиї числа, — і вимикає навчання та прогноз. Тут — чиста перевірка: чи
// живі пробіг і пожиттєві лічильники ПЛАВНО ПРОДОВЖУЮТЬ саме це авто.
//
// Безпека несиметрична навмисно, як і всюди в обліку авто. «Так» кажемо лише коли
// числа впевнено продовжують відбиток; будь-який сумнів — «ні», і тоді лишається
// VIN або вибір руками. Чужа батарея дає інші абсолютні лічильники (і пробіг на
// десятки тисяч інший), тож неперервність на ній не складеться — саме цього ми й
// хочемо.
//
// Живе в Data, бо це чиста логіка над [CarProfile] і нею користуються і блок гаража,
// і екран вибору авто: у Data це спільне надбання, а не імпорт чужого блока.
// ====================================================================================

package com.kirianov.kiasoulevplus2.Data

object CarIdentity {

    /**
     * Наскільки пробіг міг вирости між двома поглядами застосунку, км.
     *
     * Щедро, але скінченно: навіть довга дорога без телефона рідко додає стільки, а
     * чуже авто відрізнятиметься куди більше. Виросло понад це — не впізнаємо за
     * відбитком (радше пересіли в іншу машину), лишається VIN чи вибір руками.
     */
    const val MAX_ODOMETER_GROWTH_KM = 3_000.0

    /** Скільки могли додати пожиттєві лічильники за той самий час, кВт·год. */
    const val MAX_COUNTER_GROWTH_KWH = 500.0

    /**
     * Чи продовжують живі числа саме це авто.
     *
     * Умови однакові для всіх трьох величин: виросли (не впали — лічильники й пробіг
     * не вміють зменшуватись) і виросли не більше за межу правдоподібного. Без
     * відбитка ([CarProfile.hasFingerprint]) порівнювати нема з чим — одразу «ні».
     */
    fun continues(car: CarProfile, odometerKm: Double, kwhIn: Double, kwhOut: Double): Boolean {
        if (!car.hasFingerprint) return false
        return grewWithin(car.lastOdometerKm, odometerKm, MAX_ODOMETER_GROWTH_KM) &&
            grewWithin(car.lastKwhIn, kwhIn, MAX_COUNTER_GROWTH_KWH) &&
            grewWithin(car.lastKwhOut, kwhOut, MAX_COUNTER_GROWTH_KWH)
    }

    private fun grewWithin(from: Double, to: Double, maxGrowth: Double): Boolean =
        to >= from && to - from <= maxGrowth
}
