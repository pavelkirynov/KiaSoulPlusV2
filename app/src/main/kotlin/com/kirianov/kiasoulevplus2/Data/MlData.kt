package com.kirianov.kiasoulevplus2.Data

/**
 * Те, що вивчив блок прогнозу, і його поточне передбачення.
 *
 * Сховище лишається пасивним: тут немає жодного розрахунку, самі лише значення.
 */
data class MlData(
    /** Поточний прогноз. null, поки нема з чого його зробити. */
    val prediction: MlPrediction? = null,

    /** Що модель встигла вивчити і наскільки їй можна вірити. */
    val model: MlModelInfo = MlModelInfo(),

    /** Останні відрізки — з них екран малює, як витрата змінювалася. */
    val recentSegments: List<MlSegment> = emptyList(),

    /** Іде перенавчання журналом: екран на цей час блокує кнопку. */
    val retraining: Boolean = false,

    /** Чого екран просить від блока прогнозу. Блок виконає і поверне в None. */
    val request: MlRequest = MlRequest.None,
)

/**
 * Дія, якої інтерфейс просить від блока прогнозу. Як і `AppRequest`, це запит через
 * сховище, а не виклик: екрану не потрібне посилання на сам блок.
 */
enum class MlRequest {
    None,

    /** Перечитати журнал і зібрати модель з нуля: після зміни набору ознак. */
    Retrain,

    /** Забути все: і модель, і журнал. Після зміни батареї або авто. */
    Reset,
}

/**
 * Один відрізок навчання: скільки проїхали, скільки на це пішло енергії
 * і за яких умов. Саме такий рядок лягає в журнал.
 *
 * Тут навмисно лежать **сирі моменти** швидкості, а не готові ознаки моделі:
 * набір ознак іще зміниться, а журнал має лишитися придатним для перенавчання.
 * Тому [meanSpeedCubedMps] — це середнє від v³, а не куб середньої: рвана їзда
 * коштує дорожче за рівну з тією самою середньою, і саме ця різниця про це й каже.
 *
 * Швидкості в метрах за секунду, а не в км/год: куб швидкості в км/год сягає
 * мільйона, і матриця нормальних рівнянь помітно гіршає без жодної на те причини.
 */
data class MlSegment(
    /** Годинник телефона на початку відрізка: журнал має читатися очима. */
    val startedAtMs: Long,

    /**
     * Пробіг за відрізок, км.
     *
     * Кінці відрізка прив'язані до моментів, коли лічильник пробігу **змінився**,
     * тож це точна різниця двох показів, а не різниця двох округлень. Похибка
     * при цьому переїжджає з відстані в час — а часу у відрізку п'ять хвилин,
     * і десять секунд невизначеності важать куди менше, ніж 0.1 км на трьох.
     */
    val distanceKm: Double,
    val durationMs: Long,

    /** Чиста енергія батареї за відрізок, кВт·год. Додатна — віддано, тобто витрата. */
    val energyKwh: Double,

    /** Повернуто рекуперацією, кВт·год. Разом із тягою дає розклад чистої енергії. */
    val regenKwh: Double = 0.0,

    /** Віддано на тягу, кВт·год. */
    val tractionKwh: Double = 0.0,

    /** Середня швидкість, м/с: пробіг, поділений на час. */
    val meanSpeedMps: Double,

    /** Середнє від куба швидкості, (м/с)³. Опір повітря росте саме як куб. */
    val meanSpeedCubedMps: Double,

    /** Розкид швидкості, (м/с)²: рвана їзда проти рівної. */
    val speedVarianceMps: Double = 0.0,

    /** Скільки замірів швидкості потрапило у відрізок. Мало замірів — слабкі моменти. */
    val speedSamples: Int = 0,

    /** Частка часу відрізка, проведена на місці: 0 — не зупинялися, 1 — не рушали. */
    val stoppedFraction: Double = 0.0,

    /**
     * Частка тривалості, покрита замірами потужності: опитування перебивається
     * вікном монітора, і приблизно п'яту частину часу струму не видно.
     */
    val coverage: Double = 1.0,

    val ambientTempC: Double? = null,
    val batteryTempC: Double? = null,

    /**
     * Яку частку витрати з'їдає клімат, за словами самого авто. Кадр 200 каже,
     * на скільки кілометрів виріс би запас ходу з вимкненим кліматом; звідси
     * частка = приріст / (запас + приріст).
     *
     * Це пряме свідчення, а не здогад: температура за бортом показує погоду, а не
     * те, чи ввімкнена пічка. null, поки кадр 200 не приходив.
     */
    val climateShare: Double? = null,

    /** SOC з BMS на кінцях відрізка. */
    val socStartPercent: Double? = null,
    val socEndPercent: Double? = null,

    /** SOC як на панелі: з пари з точним видно буфери зверху й знизу. */
    val displaySocStartPercent: Double? = null,
    val displaySocEndPercent: Double? = null,

    /** Відрізок заряджання, а не руху: для ємності він найчистіший, для витрати марний. */
    val charging: Boolean = false,

    /** Що модель передбачала для цього відрізка ДО того, як його побачила, кВт. */
    val predictedPowerKw: Double? = null,
) {
    val distanceMeters: Double get() = distanceKm * 1000.0

    val meanSpeedKmh: Double get() = meanSpeedMps * MPS_TO_KMH

    /** Витрата на відрізку, Вт·год/км. Null, якщо відрізок нікуди не їхав. */
    val whPerKm: Double? get() = if (distanceKm > 0.0) energyKwh * 1000.0 / distanceKm else null

    /** Середня потужність за відрізок, кВт. Це і є відгук, якого вчиться модель. */
    val averagePowerKw: Double?
        get() = if (durationMs > 0) energyKwh / (durationMs / MS_PER_HOUR) else null

    /** Скільки відсотків SOC з'їв відрізок. Додатне — розряд. */
    val socDropPercent: Double?
        get() {
            val from = socStartPercent ?: return null
            val to = socEndPercent ?: return null
            return from - to
        }

    /**
     * Яку частку тяги повернула рекуперація. Висока частка — це спуск, а спуск
     * модель бачити не вміє: висоти в застосунку немає. Такий відрізок краще
     * зважити нижче, ніж навчити на ньому неправди.
     *
     * Накат — рекуперація без жодної тяги — це крайній випадок того самого спуску,
     * а не нуль: ділення тут повернуло б 0/0 або ∞, і формальний нуль тихо провів
     * би такий відрізок повз захист у навчання.
     */
    val regenFraction: Double
        get() = when {
            tractionKwh > 0.0 -> regenKwh / tractionKwh
            regenKwh > 0.0 -> Double.POSITIVE_INFINITY
            else -> 0.0
        }

    private companion object {
        const val MS_PER_HOUR = 3_600_000.0
        const val MPS_TO_KMH = 3.6
    }
}

/**
 * Прогноз на поточний момент.
 *
 * Межі [rangeFromKm] і [rangeToKm] несиметричні навмисно: промахнутися в бік
 * «з'їло більше, ніж думали» можна значно сильніше, ніж навпаки, і рівний
 * «плюс-мінус» цю асиметрію приховав би.
 *
 * [measuredBand] каже, звідки взялася ширина: true — з фактичних промахів на
 * блоках по десять кілометрів, false — з апріорної оцінки, поки промахів
 * ще замало. Число на екрані має чесно казати, наскільки воно виміряне.
 */
data class MlPrediction(
    val rangeKm: Double,
    val rangeFromKm: Double,
    val rangeToKm: Double,

    /** Скільки насправді лишилося, % корисної енергії. Це не панельний SOC. */
    val realPercent: Double,

    val usableEnergyRemainingKwh: Double,

    /** Витрата, на якій побудований прогноз, Вт·год/км. */
    val whPerKm: Double,

    val measuredBand: Boolean = false,

    /** Той самий залишок для кількох сталих швидкостей. */
    val scenarios: List<RangeScenario> = emptyList(),
)

/** Залишок ходу, якщо всю дорогу їхати з однією швидкістю. */
data class RangeScenario(
    val speedKmh: Double,
    val rangeKm: Double,
    val whPerKm: Double,
)

/**
 * Скільки моделі відомо і чи варто вже вірити її числу.
 */
data class MlModelInfo(
    val segments: Int = 0,
    val learnedKm: Double = 0.0,

    /** Блоки по 10 км, на яких перевірялася чесність інтервалу. */
    val blocks: Int = 0,

    /** Вивчена корисна ємність батареї, кВт·год. Не константа з даташита. */
    val usableCapacityKwh: Double? = null,

    /**
     * Скільки кВт·год виходить на повний прохід шкали від ста до нуля — сира сума
     * виміряного, без жодної моделі. Незалежна перевірка вивченої кривої.
     */
    val averageCapacityKwh: Double? = null,

    /** Скільки відсотків шкали загалом пройшло через вимірювання. */
    val measuredScalePercent: Double = 0.0,

    /** Вивчена ємність відносно очікуваної від перепаковки, %. */
    val capacityVersusNominalPercent: Double? = null,

    /**
     * У скільки разів пакет більший за рідний, з паспорта якого BMS досі рахує
     * відсотки. Це і є множник, на який помиляється бортовий запас ходу.
     */
    val timesLargerThanOriginal: Double? = null,

    /** Справжні краї шкали: точний SOC, на якому панель показує 0 і 100. */
    val floorSocPercent: Double? = null,
    val ceilingSocPercent: Double? = null,

    /** Вивчений постійний відбір (електроніка, клімат на стоянці), кВт. */
    val auxPowerKw: Double? = null,

    /** Середня помилка передбачення, Вт·год/км: модель питають ДО того, як показати відповідь. */
    val maeWhPerKm: Double? = null,

    /**
     * Наскільки горбисто їздить цей водій, метри набору висоти на корінь із кілометра.
     * Виміряно за розкидом промахів: самих висот застосунок не бачить.
     */
    val terrainRoughness: Double? = null,

    /** Що з ознак уже вивчене з даних, а не взяте з фізики: від 0 до 1 на кожну. */
    val readiness: List<Pair<String, Double>> = emptyList(),

    val confidence: MlConfidence = MlConfidence.None,

    /** Годинник телефона на момент останнього навчання. */
    val updatedAtMs: Long? = null,
) {
    val isTrained: Boolean get() = confidence != MlConfidence.None
}

/**
 * Наскільки моделі можна вірити. Окремий тип, а не число: на екрані це підпис,
 * і хай межі живуть в одному місці, а не розповзаються по картках.
 */
enum class MlConfidence {
    /** Даних ще нема — показуємо фізичне наближення, а не прогноз. */
    None,

    /** Модель уже вчиться, але число ще плаває. */
    Learning,

    /** Числу можна вірити з поправкою на інтервал. */
    Fair,

    /** Модель стабільна: інтервал вузький, помилка мала. */
    Good,
}
