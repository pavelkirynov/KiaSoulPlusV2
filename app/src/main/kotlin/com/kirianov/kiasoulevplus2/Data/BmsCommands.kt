package com.kirianov.kiasoulevplus2.Data

/**
 * Довідник CAN-запитів до BMS. Єдине місце, де живуть тексти команд —
 * декодери та сервіси беруть їх звідси, а не дублюють рядки в себе.
 */
object BmsCommands {
    /** CAN-заголовок блока BMS. */
    const val HEADER_BMS = "7E4"

    /** Основний кадр: SOC, напруга, струм, температури. */
    const val REQUEST_BATTERY_MAIN = "21 01"

    /**
     * Другий кадр батареї: знос комірок і справжні межі температур.
     *
     * Питається рідко, а не щоопитування, і причина не в економії: знос міряється
     * місяцями, а межі температур — хвилинами. Питати їх щосекунди означало б
     * витрачати шину на числа, які за секунду не змінюються.
     */
    const val REQUEST_PACK_HEALTH = "21 05"

    /**
     * Кадри з напругами комірок: по 32 комірки в кожному, разом 96.
     * Порядок важливий — комірки склеюються в один масив саме в цій послідовності.
     */
    val REQUEST_CELL_VOLTAGES = listOf("21 02", "21 03", "21 04")

    /**
     * VIN: функціональний заголовок і стандартний OBD-запит.
     *
     * Єдина річ на шині, яка відповідає на питання «а це те саме авто». Питаємо
     * функціонально (7DF), а не конкретний блок: VIN віддає не завжди той самий
     * модуль, і адресний запит на частині машин просто мовчить.
     */
    const val HEADER_OBD = "7DF"
    const val REQUEST_VIN = "09 02"

    // Запиту пробігу тут немає навмисно: на Soul EV 27 kWh одометра немає в жодному
    // DID. Він приходить широкомовним кадром 4F0 і читається в режимі монітора.
}

/**
 * Запит до блока тиску в шинах.
 *
 * У SoulEVSpy тиску немає взагалі — там лише швидкості обертання коліс. Але блок
 * у цій машині є й на шині озивається: під час першого опитування помилок адреса
 * 7A0 відповіла «зайнятий, зачекай». Набір `22 C0 0B` — той, яким користуються
 * Torque й Car Scanner на Hyundai/Kia того ж покоління.
 *
 * Тексти команд живуть у Data, як і решта: блок Bluetooth не має права знати про
 * декодери, а декодер — про те, хто й коли питає.
 */
object TireCommands {
    /** CAN-заголовок блока тиску в шинах. */
    const val HEADER = "7A0"

    /** Читання даних усіх чотирьох датчиків одним запитом. */
    const val REQUEST = "22C00B"
}
