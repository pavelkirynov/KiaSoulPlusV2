package com.kirianov.kiasoulevplus2.Data

/**
 * Налаштування, які обирає користувач. Зберігаються між запусками.
 */
data class Settings(
    /**
     * Чи під'єднуватися до адаптера самостійно.
     *
     * Типово увімкнено: без цього моделі вчаться лише тоді, коли хтось згадав
     * натиснути кнопку, а найцінніші дані — щоденні поїздки — просто не
     * потрапляють у журнал.
     */
    val autoConnect: Boolean = true,

    /**
     * Чи вести журнал діагностики.
     *
     * Типово увімкнено. Ціна — кілька мегабайтів на день у власній теці
     * застосунку (старіші рядки витісняються), користь — можливість відповісти
     * «чому», а не гадати за знімком екрана.
     */
    val journal: Boolean = true,

    /**
     * Адреси пристроїв, поява яких будить застосунок. Порожньо — не будити.
     *
     * Задум простий: магнітола з'єднується з телефоном щоразу, коли ви сіли в
     * авто, — це найнадійніша ознака «поїхали» з усіх, що є в телефона. Сам ELM
     * для цього годиться гірше: клони підіймають зв'язок не самі, а лише коли до
     * них під'єднуються, тобто саме тоді, коли застосунок уже працює.
     *
     * ЧОМУ СПИСОК, А НЕ ОДНА АДРЕСА. Пристрій, який ловить «ви сіли в авто», не
     * завжди один і той самий: магнітола на частині прошивок з'єднується то
     * профілем A2DP, то гарнітурою, і адреси в них різні; а ще буває друга машина
     * або гарнітура в шоломі. Одна адреса означала, що всі інші приводи
     * відкидаються мовчки — у журналі це видно рядками «це не той, пропускаємо».
     */
    val wakeOnDeviceAddresses: Set<String> = emptySet(),

    /**
     * Пороги фарбування комірок — свої для кожного режиму значень.
     *
     * Живуть у налаштуваннях, а не в теці авто: це про те, з якої різниці ВИ
     * хочете бачити колір, а не про саму батарею. Різниця в спокої й під струмом
     * відрізняється в разі, тому й пороги окремі — див. [CellPalettes].
     */
    val cellPalettes: CellPalettes = CellPalettes(),

    /**
     * Умови далекої дороги: відстань, ціна кіловат-години й потужність станції.
     *
     * У налаштуваннях, а не на екрані на один раз: ціну електрики й ту станцію,
     * якою ви користуєтесь, набирати щоразу заново — зайва робота, а відстань
     * найчастіше та сама, бо далека дорога в людини зазвичай одна й та сама.
     */
    val trip: TripConditions = TripConditions(),

    /**
     * Чи це вже прочитані з диска налаштування, а не типові.
     *
     * Не зберігається — живе лише в пам'яті. Потрібне тим, хто мусить відрізнити
     * «користувач так обрав» від «ще не читали з диска»: екран не має блимати
     * типовими значеннями, а блоки — будуватися на них.
     */
    val loaded: Boolean = false,
) {
    /** Чи будить застосунок поява саме цього пристрою. */
    fun wakesOn(address: String): Boolean =
        address.isNotEmpty() && wakeOnDeviceAddresses.any { it.equals(address, ignoreCase = true) }

    val wakesOnAnything: Boolean get() = wakeOnDeviceAddresses.isNotEmpty()
}
