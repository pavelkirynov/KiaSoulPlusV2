package com.kirianov.kiasoulevplus2.Data

/**
 * Налаштування, які обирає користувач. Зберігаються між запусками.
 */
data class Settings(
    /**
     * Чи під'єднуватися до адаптера самостійно.
     *
     * Типово увімкнено: без цього моделі вчаться лише тоді, коли хтось згадав
     * натиснути кнопку, а найцінніші дані — щоденні поїздки — просто не
     * потрапляють у журнал.
     */
    val autoConnect: Boolean = true,

    /**
     * Чи вести журнал діагностики.
     *
     * Типово увімкнено. Ціна — кілька мегабайтів на день у власній теці
     * застосунку (старіші рядки витісняються), користь — можливість відповісти
     * «чому», а не гадати за знімком екрана.
     */
    val journal: Boolean = true,

    /**
     * Адреса пристрою, поява якого будить застосунок. Порожньо — не будити.
     *
     * Задум простий: магнітола з'єднується з телефоном щоразу, коли ви сіли в
     * авто, — це найнадійніша ознака «поїхали» з усіх, що є в телефона. Сам ELM
     * для цього годиться гірше: клони підіймають зв'язок не самі, а лише коли до
     * них під'єднуються, тобто саме тоді, коли застосунок уже працює.
     */
    val wakeOnDeviceAddress: String = "",
)
