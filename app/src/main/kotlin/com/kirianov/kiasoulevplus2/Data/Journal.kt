package com.kirianov.kiasoulevplus2.Data

/**
 * Журнал діагностики: що застосунок бачив і коли.
 *
 * НАВІЩО ВІН ПОТРІБЕН. Усе цікаве відбувається між опитуваннями — за секунди й
 * долі секунди. Екран показує ЗРІЗ: те, що є зараз. Він не відповідає на
 * запитання «чому», бо не пам'ятає, що було хвилину тому: чи росла енергія, коли
 * зникла ознака заряджання, чи взагалі приходили кадри, поки авто їхало.
 * Переписати це вручну неможливо, тож застосунок записує сам.
 *
 * Тут — тільки стан файлу для екрана. Самі рядки веде блок tools/journal.
 */
data class Journal(
    val sizeBytes: Long = 0L,
    val lines: Long = 0L,

    /** Повний шлях: потрібен інтерфейсу, щоб віддати файл кнопці «Поділитися». */
    val path: String = "",

    val request: JournalRequest = JournalRequest.None,
    val lastError: String = "",
) {
    val hasFile: Boolean get() = path.isNotEmpty() && sizeBytes > 0L
}

enum class JournalRequest {
    None,

    /** Стерти й почати заново: перед контрольною поїздкою так робити правильно. */
    Clear,
}
