// ====================================================================================
// ТИСК У ШИНАХ (TireData)
//
// У SoulEVSpy цього немає — там лише швидкості обертання коліс. Але блок тиску в
// цій машині Є і на шині відповідає: під час першого опитування помилок адреса
// 7A0 озвалася «зайнятий, зачекай» (0x78), тобто модуль живий і слухає.
//
// Тому тиск читається не широкомовним кадром, а запитом до окремого блока:
// `7A0 → 22 C0 0B`. Це набір, яким користуються Torque й Car Scanner на
// Hyundai/Kia того ж покоління; зміщення в ньому — здогад, і саме тому СИРА
// ВІДПОВІДЬ ІДЕ В ЖУРНАЛ ЦІЛКОМ. Якщо байти виявляться не там, наступний журнал
// покаже, де вони насправді, і виправлення обійдеться однією константою.
//
// ОДИНИЦІ. Датчик віддає тиск у 0.2 psi на крок — так у всіх відомих наборах для
// цих машин. На екран іде бар, бо саме в барах написано на стійці дверей і саме в
// них накачують шини тут.
// ====================================================================================

package com.kirianov.kiasoulevplus2.Data

/**
 * Тиск і температура кожної шини.
 *
 * [known] хибне, поки блок не відповів: нуль тут — законне свідчення (спущене
 * колесо), і плутати його з «не питали» не можна.
 *
 * Порядок колес той самий, що й у кадрі 4B0: переднє ліве, переднє праве, заднє
 * ліве, заднє праве. Він теж здогад, і перевіряється так само — спустити одне
 * колесо й подивитися, котре число впало.
 */
data class TireData(
    val known: Boolean = false,

    /** Тиск чотирьох шин, бар. */
    val pressuresBar: List<Double> = emptyList(),

    /** Температура чотирьох датчиків, °C. */
    val tempsC: List<Double> = emptyList(),
) {
    val hasPressures: Boolean get() = known && pressuresBar.size == WHEELS

    /** Найнижчий тиск: саме він відповідає на питання «чи все гаразд». */
    val minPressureBar: Double? get() = pressuresBar.minOrNull()

    /** Розкид тиску по колесах, бар. */
    val spreadBar: Double
        get() {
            val min = pressuresBar.minOrNull() ?: return 0.0
            val max = pressuresBar.maxOrNull() ?: return 0.0
            return max - min
        }

    companion object {
        const val WHEELS = 4

        /** Крок датчика, psi. */
        const val PSI_PER_STEP = 0.2

        /** Один psi в барах. */
        const val BAR_PER_PSI = 0.0689476
    }
}
