// ====================================================================================
// ІСТОРІЯ ЗАМІРІВ КОМІРОК (CellHistory)
//
// Замір комірок має сенс лише в порівнянні. Одна табличка напруг не каже нічого:
// 3.62 В — це добре чи погано? Відповідь дає тільки друга така сама табличка,
// знята іншого дня, і різниця між ними.
//
// Найгостріше це перед перепакуванням: треба бачити пакет до і після, а між ними
// тижні. Тримати це в голові чи в скриншотах не вийде.
//
// Запис самодостатній навмисно. У ньому лежать не лише напруги, а й пробіг, заряд і
// температура тієї миті: без них порівняння двох замірів нічого не варте — комірки
// на 20 % і на 90 % шкали, на теплій і на холодній батареї показують різне, і
// різниця між замірами була б різницею умов, а не пакетів.
// ====================================================================================

package com.kirianov.kiasoulevplus2.Data

/**
 * Один збережений замір.
 *
 * [restVolts] є завжди — це те, що комірки показували в момент запису. Решта
 * з'являється тільки в записах із тесту під навантаженням: без розмаху струму ні
 * мінімумів під навантаженням, ні опору вивести нема з чого.
 */
data class CellRecord(
    val atMs: Long,
    val odometerKm: Double,
    val socPercent: Double,
    val batteryTempC: Double,

    /** Напруги комірок, В. Порожньо запис не буває: без них він ні про що. */
    val restVolts: List<Double>,

    /** Найнижча напруга кожної комірки за тест, В. Порожньо — тесту не було. */
    val minVolts: List<Double> = emptyList(),

    /** Надлишковий опір відносно середньої комірки, мОм. Порожньо — не виведено. */
    val excessMilliOhm: List<Double> = emptyList(),

    /** Скільки проходів увійшло в тест. Нуль — це простий замір, а не тест. */
    val sweeps: Int = 0,

    /** Розмах струму за тест, А: за ним видно, чи можна вірити опору. */
    val currentSpreadA: Double = 0.0,

    /**
     * Найбільше навантаження за тест, кВт: під ним і знято найглибші просадки.
     *
     * Зберігається разом із заміром, бо без нього самі напруги нічого не значать:
     * «мінімум 3.41 В» під десятьма кіловатами й під сімдесятьма — два різні
     * висновки, а на екрані вони виглядали б однаково.
     */
    val peakLoadKw: Double = 0.0,
) {
    val fromLoadTest: Boolean get() = sweeps > 0

    val cells: Int get() = restVolts.size

    /** Розкид напруг у цьому замірі, В — найкоротша характеристика пакета. */
    val spreadVolts: Double
        get() = if (restVolts.isEmpty()) 0.0 else (restVolts.max() - restVolts.min())
}

/** Що екран просить зробити з історією. */
enum class CellHistoryRequest {
    None,

    /** Зберегти те, що зараз на екрані, як окремий замір. */
    Save,

    /** Видалити обраний запис. */
    Delete,
}

data class CellHistory(
    /** Найновіші — першими: саме їх і дивляться. */
    val records: List<CellRecord> = emptyList(),

    val request: CellHistoryRequest = CellHistoryRequest.None,

    /** Час запису, якого стосується прохання видалити. */
    val requestAtMs: Long = 0L,

    /** Чи прочитано історію з диска. До того порожній список — не «немає». */
    val loaded: Boolean = false,
) {
    val isEmpty: Boolean get() = records.isEmpty()
}
