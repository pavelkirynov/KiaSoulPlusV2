package com.kirianov.kiasoulevplus2.services.bluetooth

/**
 * Те, що вміє адаптер ELM327.
 *
 * Крім звичайного «команда → відповідь до промпта», потрібні низькорівневі операції
 * для режиму монітора: там промпт не приходить взагалі, кадри сиплються потоком,
 * а зупиняється це надсиланням одного пробілу.
 *
 * Винесено інтерфейсом, щоб ElmCANBridge можна було перевірити тестами без
 * Bluetooth і без авто — зокрема неподільність запиту й коректний вихід з монітора.
 */
interface ElmAdapter {

    /** Надсилає команду і читає відповідь до промпта «>». */
    suspend fun sendCommand(command: String): String

    /** Пише байти як є, без очікування відповіді. Потрібно для «AT MA» і пробілу. */
    suspend fun writeRaw(text: String)

    /**
     * Забирає все, що вже прийшло, і повертає як є — разом із неповним «хвостом».
     *
     * Саме шматками, а не рядками: читання «до \r» з таймаутом віддавало обрізану
     * половину кадру як повний рядок, і байти зсувалися. Межі рядків знаходить той,
     * хто збирає вікно, коли вже має весь буфер.
     */
    suspend fun readAvailable(): String

    /** Викидає все, що лишилося в буфері. */
    suspend fun flushInput()
}
