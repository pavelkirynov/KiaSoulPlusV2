// ====================================================================================
// РОЗДІЛИ Й СТОРІНКИ (AppScreen)
//
// Спершу сторінок було п'ять і вони лежали в один ряд. Поки все в застосунку було
// про батарею, це працювало. Щойно з'явилися системи авто, стало видно, що ряд
// доростає до десятка вкладок, у якому не знайти нічого.
//
// Тому рівнів два: унизу РОЗДІЛИ, всередині розділу — його сторінки. Розділ — це
// не «схожі екрани», а окрема галузь: батарея, авто, ручна робота з шиною,
// налаштування самого застосунку.
//
// ЧОМУ ЕКСПЕРИМЕНТИ ОКРЕМИМ РОЗДІЛОМ, А НЕ ВСЕРЕДИНІ «АВТО». Ручні запити на шину
// потрібні однаково і батареї, і авто: ними знаходять нові кадри й перевіряють
// здогади. Сховати їх під одну галузь означало б щоразу ходити туди кружним шляхом.
// ====================================================================================

package com.kirianov.kiasoulevplus2.Interface

/** Сторінка — один екран. Заголовок бачить людина у верхньому ряду. */
enum class AppPage(val title: String) {
    MAIN("Головна"),
    PREDICTION("Прогноз"),
    CELLS("Комірки"),
    CAR_OVERVIEW("Огляд"),
    CAR_FAULTS("Помилки"),
    PROBE("Запити"),
    SETTINGS("Налаштування"),
}

/**
 * Розділ — галузь, у якій живуть сторінки.
 *
 * [pages] порожній не буває: розділ без сторінок — це просто мертва кнопка внизу.
 */
enum class AppSection(val title: String, val pages: List<AppPage>) {
    BATTERY("Батарея", listOf(AppPage.MAIN, AppPage.PREDICTION, AppPage.CELLS)),
    CAR("Авто", listOf(AppPage.CAR_OVERVIEW, AppPage.CAR_FAULTS)),
    EXPERIMENTS("Експерименти", listOf(AppPage.PROBE)),
    SETTINGS("Налаштування", listOf(AppPage.SETTINGS)),
}
